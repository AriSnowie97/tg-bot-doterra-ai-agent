# - Для кожного факту познач, з якого фрагмента він узятий, у форматі [chunk_id] в кінці речення. Ці мітки бекенд перетворить на кнопки з посиланнями — сам URL ти ніколи не пишеш.


# ---------------------------------------------------------------------------
# Хелпер для підставлення RAG-контексту
# ---------------------------------------------------------------------------

def build_system_prompt(
    context_chunks: list[dict] | None = None,
    suggest_specialist: bool = False,
) -> str:
    """Збирає системний промпт із підставленим RAG-контекстом.

    Args:
        context_chunks: список chunk-словників із полями
                        ``chunk_id`` та ``content``.
                        Якщо None або порожній — підставляє плейсхолдер.
        suggest_specialist: якщо True — LLM отримує пряму інструкцію
                            проактивно запропонувати контакти Наталії
                            Котелянської у відповіді.

    Returns:
        Рядок готового системного промпту.
    """
    if not context_chunks:
        context_text = "(контекст не знайдено — попроси користувача уточнити запит)"
    else:
        parts: list[str] = []
        for chunk in context_chunks:
            product_slug = chunk.get("product_slug", "unknown")
            content = chunk.get("content", "").strip()
            parts.append(f"[product_slug: {product_slug}]\n{content}")
        context_text = "\n\n---\n\n".join(parts)

    specialist_block = SPECIALIST_CONTACT_BLOCK if suggest_specialist else (
        "(контакти не потрібні для цього запиту — пропусти цей блок)"
    )

    return SYSTEM_PROMPT.format(context=context_text, specialist_block=specialist_block)
