# ---------------------------------------------------------------------------
# Хелпер для підставлення RAG-контексту
# ---------------------------------------------------------------------------

def build_post_prompt(context_chunks: list[dict] | None = None) -> str:
    """Збирає системний промпт для генерації посту із підставленим RAG-контекстом.

    Args:
        context_chunks: список chunk-словників із полями
                        ``chunk_id`` та ``content``.
                        Якщо None або порожній — підставляє заглушку.

    Returns:
        Рядок готового системного промпту для генерації посту.
    """
    if not context_chunks:
        context_text = "(контекст не знайдено — напиши загальний пост про переваги ефірних олій doTERRA)"
    else:
        parts: list[str] = []
        for chunk in context_chunks:
            chunk_id = chunk.get("chunk_id", "unknown")
            content = chunk.get("content", "").strip()
            parts.append(f"[{chunk_id}]\n{content}")
        context_text = "\n\n---\n\n".join(parts)

    return POST_SYSTEM_PROMPT.format(context=context_text)
